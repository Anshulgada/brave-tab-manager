"""Build script for Tabman Rust WebAssembly SIMD acceleration module.

Compiles crates/tabman-wasm with wasm32-unknown-unknown and +simd128 target features,
copies the resulting binary into extension/public/tabman_wasm.wasm, and generates
extension/src/rust-wasm-binary.ts with embedded base64 bytes for zero-latency inlining.
"""

from __future__ import annotations

import base64
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CRATE_DIR = ROOT / "crates" / "tabman-wasm"
OUT_WASM = ROOT / "extension" / "public" / "tabman_wasm.wasm"
OUT_TS = ROOT / "extension" / "src" / "rust-wasm-binary.ts"


def main() -> int:
    cargo = os.environ.get("CARGO", "cargo")
    cargo_bin = "cargo.exe" if sys.platform == "win32" else "cargo"
    cargo_path = Path.home() / ".cargo" / "bin" / cargo_bin
    if cargo_path.exists():
        cargo = str(cargo_path)

    print("==> Building tabman-wasm for wasm32-unknown-unknown with +simd128...")
    env = os.environ.copy()
    env["RUSTFLAGS"] = "-C target-feature=+simd128"

    cmd = [
        cargo,
        "build",
        "--target",
        "wasm32-unknown-unknown",
        "--release",
        "--manifest-path",
        str(CRATE_DIR / "Cargo.toml"),
    ]

    result = subprocess.run(cmd, env=env, cwd=ROOT)
    if result.returncode != 0:
        print("ERROR: cargo build failed.")
        return result.returncode

    built_wasm = (
        ROOT / "target" / "wasm32-unknown-unknown" / "release" / "tabman_wasm.wasm"
    )
    if not built_wasm.exists():
        print(f"ERROR: Expected artifact {built_wasm} not found.")
        return 1

    wasm_bytes = built_wasm.read_bytes()
    size_kb = len(wasm_bytes) / 1024.0
    print(f"==> Compiled tabman_wasm.wasm ({size_kb:.2f} KB)")

    OUT_WASM.parent.mkdir(parents=True, exist_ok=True)
    OUT_WASM.write_bytes(wasm_bytes)
    print(f"==> Copied to {OUT_WASM.relative_to(ROOT)}")

    # Generate embedded TypeScript module
    b64 = base64.b64encode(wasm_bytes).decode("ascii")
    ts_content = f"""// Auto-generated by scripts/build_wasm.py - DO NOT EDIT MANUALLY
// Embedded 128-bit SIMD WebAssembly binary for Tabman tab clustering and vector search.

export const TABMAN_WASM_BASE64 = '{b64}';
export const TABMAN_WASM_BYTE_LENGTH = {len(wasm_bytes)};
"""
    OUT_TS.write_text(ts_content, encoding="utf-8")
    rel_ts = OUT_TS.relative_to(ROOT)
    ts_kb = len(ts_content) / 1024.0
    print(f"==> Generated {rel_ts} ({ts_kb:.2f} KB)")
    print("[OK] Rust WASM build complete!")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
